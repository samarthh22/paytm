import mongoose from "mongoose";
import { Schema, Types } from "mongoose";

const user = new Schema({
  username: {
    type: String,
    required: true,
    unique: true,
    trim: true,
    lowercase: true,
  },
  password: {
    type: String,
    required: true,
  },
  firstName: {
    type: String,
    required: true,
    trim: true,
  },
  lastName: {
    type: String,
    required: true,
    trim: true,
  },
});
const UserModel = mongoose.model("users", user);
const account = new Schema({
  userId: {
    type: Schema.Types.ObjectId,
    ref: "User",
    required: true,
  },
  balance: {
    type: Number,
    required: true,
  },
});

const AccountModel = mongoose.model("Accounts", account);

export { UserModel, AccountModel };
